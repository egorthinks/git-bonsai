#!/usr/bin/env node
// Bundles the compiled engine (dist/src, plain CommonJS, zero deps) into a
// single browser script: docs/engine.js, exposing a global `Bonsai`.
// No bundler dependency — the module graph is ours and flat, so a 30-line
// CJS loader is enough. Run after `npm run build`.
//
// Excluded: action/cli (node-only entrypoints), index/encode/png (pull in
// zlib; the browser renders straight to <canvas> and encodes GIFs with the
// hand-rolled encoder, which only needs a one-line Buffer shim).
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const distDir = path.join(root, 'dist', 'src');

const EXCLUDE = new Set(['action.js', 'cli.js', 'index.js', 'encode.js', 'png.js']);

// the browser-facing surface: everything the playground page needs
const API = `
const data = require('./data');
const palette = require('./palette');
exports.normalize = data.normalize;
exports.synthMetrics = data.synthMetrics;
exports.deriveDna = require('./dna').deriveDna;
exports.buildSkeleton = require('./skeleton').buildSkeleton;
exports.applyThickness = require('./thickness').applyThickness;
exports.buildPalette = palette.buildPalette;
exports.seasonFromDate = palette.seasonFromDate;
exports.PALETTE_SIZE = palette.PALETTE_SIZE;
exports.TRANSPARENT = palette.TRANSPARENT;
exports.renderFrame = require('./render').renderFrame;
exports.windFrames = require('./animate').windFrames;
exports.growthFrames = require('./animate').growthFrames;
exports.fitBox = require('./raster').fitBox;
exports.cropFrame = require('./raster').cropFrame;
exports.encodeGif = require('./gif').encodeGif;
exports.makeRng = require('./seed').makeRng;
`;

const modules = {};
for (const file of fs.readdirSync(distDir)) {
  if (!file.endsWith('.js') || EXCLUDE.has(file)) continue;
  modules[file.slice(0, -3)] = fs.readFileSync(path.join(distDir, file), 'utf8');
}
modules['__api'] = API;

const out = [];
out.push('// generated by scripts/build-playground.js — do not edit by hand');
out.push('var Bonsai = (() => {');
// gif.js builds its output with Buffer.from(number[]); a Uint8Array is a
// drop-in for the browser (Blob accepts it directly)
out.push('const Buffer = { from: (a) => Uint8Array.from(a) };');
out.push('const __defs = {');
for (const [name, src] of Object.entries(modules)) {
  out.push(`${JSON.stringify(name)}: function (exports, require, module) {`);
  out.push(src);
  out.push('},');
}
out.push('};');
out.push(`const __cache = {};
function __require(name) {
  const key = name.replace(/^\\.\\//, '');
  if (!(key in __defs)) return {}; // node-only imports (fs) are never called in the browser
  if (__cache[key]) return __cache[key].exports;
  const module = { exports: {} };
  __cache[key] = module;
  __defs[key](module.exports, __require, module);
  return module.exports;
}
return __require('__api');
})();`);

fs.writeFileSync(path.join(root, 'docs', 'engine.js'), out.join('\n'));
const kb = Math.round(fs.statSync(path.join(root, 'docs', 'engine.js')).size / 1024);
console.log(`wrote docs/engine.js (${kb} KB)`);
